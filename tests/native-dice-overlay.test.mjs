import test from 'node:test';
import assert from 'node:assert/strict';
import {EventEmitter} from 'node:events';
import {nativeDiceOverlay} from '../dist/main/native-dice-overlay.js';

test('native dice overlay is private, input-transparent and owned for its entire lifetime', {skip:process.platform!=='win32'},()=>{
  const contents=new EventEmitter();
  const owner=Object.assign(new EventEmitter(),{webContents:contents,isDestroyed:()=>false,isVisible:()=>true,isMinimized:()=>false,isFocused:()=>true,getContentBounds:()=>({x:10,y:20,width:800,height:600})});
  const handle=nativeDiceOverlay(owner);
  assert.equal(handle({url:'https://example.com',frameName:'odm-native-dice-overlay'}),null);
  assert.equal(handle({url:'about:blank',frameName:'other'}),null);
  const allowed=handle({url:'about:blank',frameName:'odm-native-dice-overlay'});
  assert.equal(allowed.action,'allow');
  const options=allowed.overrideBrowserWindowOptions;
  assert.equal(options.parent,owner);
  assert.equal(options.transparent,true);
  assert.equal(options.focusable,false);
  assert.equal(options.skipTaskbar,true);
  assert.deepEqual(options.webPreferences,{sandbox:true,contextIsolation:true,nodeIntegration:false,zoomFactor:1});
  let bounds,passThrough,shown=0,hidden=0,destroyed=false,childHandler;
  const childContents=Object.assign(new EventEmitter(),{setWindowOpenHandler:handler=>{childHandler=handler}});
  const child=Object.assign(new EventEmitter(),{webContents:childContents,isDestroyed:()=>destroyed,setBounds:value=>{bounds=value},setIgnoreMouseEvents:(value)=>{passThrough=value},showInactive:()=>{shown++},hide:()=>{hidden++},destroy:()=>{destroyed=true}});
  contents.emit('did-create-window',child,{frameName:'odm-native-dice-overlay'});
  assert.deepEqual(bounds,{x:10,y:20,width:800,height:600});
  assert.equal(passThrough,true);
  assert.equal(shown,1);
  assert.deepEqual(handle({url:'about:blank',frameName:'odm-native-dice-overlay'}),{action:'deny'});
  assert.deepEqual(childHandler({url:'https://example.com'}),{action:'deny'});
  let prevented=false;
  childContents.emit('will-navigate',{preventDefault(){prevented=true}});
  assert.equal(prevented,true);
  owner.emit('minimize');
  assert.equal(hidden,1);
  owner.getContentBounds=()=>({x:30,y:40,width:900,height:700});
  owner.emit('resize');
  assert.deepEqual(bounds,{x:30,y:40,width:900,height:700});
  owner.emit('closed');
  assert.equal(destroyed,true);
});
